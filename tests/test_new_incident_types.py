"""The five incident types added on 2026-10-28, plus severity scoring and
remediation. Sample events are generated by simulation/generate_scenario.py.
No AWS access required."""

import copy
import json
from pathlib import Path

import pytest

import incident_processor as ip

EVENTS = Path(__file__).parent / "events"


def load(name):
    return json.loads((EVENTS / name).read_text())


def detail(name):
    return copy.deepcopy(load(name)["detail"])


def report_for(d):
    return ip.build_report({"detail": d})


# --- the five types ----------------------------------------------------------

@pytest.mark.parametrize(
    "event_file,event_name,category,tactic,score,severity",
    [
        # base 55 + 10 (key created for a different user)
        ("create_access_key.json", "CreateAccessKey", "identity_creation", "persistence", 65, "HIGH"),
        # base 75
        ("deactivate_mfa_device.json", "DeactivateMFADevice", "mfa_tampering", "defense_evasion", 75, "HIGH"),
        # base 70 + 20 (trusts another account)
        ("update_assume_role_policy.json", "UpdateAssumeRolePolicy", "role_trust_change",
         "privilege_escalation", 90, "CRITICAL"),
        # base 50 + 20 (0.0.0.0/0) + 10 (SSH)
        ("authorize_sg_ingress.json", "AuthorizeSecurityGroupIngress", "network_exposure",
         "initial_access", 80, "HIGH"),
        # base 85 + 5 (7-day window)
        ("schedule_key_deletion.json", "ScheduleKeyDeletion", "kms_key_destruction", "impact", 90, "CRITICAL"),
    ],
)
def test_new_incident_types(event_file, event_name, category, tactic, score, severity):
    event = load(event_file)
    assert event["detail-type"] == "AWS API Call via CloudTrail"
    r = ip.build_report(event)
    assert r["event_name"] == event_name
    assert (r["category"], r["tactic"]) == (category, tactic)
    assert (r["severity_score"], r["severity"]) == (score, severity)
    assert sum(f["points"] for f in r["score_factors"]) == score
    assert r["recommended_actions"] and r["remediation"]


def test_every_new_type_has_a_terraform_rule():
    tf = (Path(__file__).parents[1] / "terraform" / "main.tf").read_text()
    for rule in ("identity-creation", "mfa-tampering", "role-trust-change", "network-exposure", "kms-key-destruction"):
        assert f"{rule} = {{" in tf


def test_original_rules_keep_their_severity():
    for name, expected in (("AttachUserPolicy", "HIGH"), ("StopLogging", "CRITICAL"),
                           ("PutBucketPolicy", "HIGH"), ("UnknownCall", "MEDIUM")):
        assert ip.classify(name)["severity"] == expected


# --- scoring modifiers ---------------------------------------------------------

def test_admin_policy_raises_score():
    d = detail("create_access_key.json")
    d.update(eventName="AttachUserPolicy", requestParameters={
        "userName": "x", "policyArn": "arn:aws:iam::aws:policy/AdministratorAccess"})
    r = report_for(d)
    assert r["severity_score"] == 85 and r["severity"] == "CRITICAL"


def test_inline_star_star_policy_counts_as_admin():
    d = detail("create_access_key.json")
    d.update(eventName="PutUserPolicy", requestParameters={
        "userName": "x", "policyName": "p",
        "policyDocument": json.dumps({"Statement": {"Effect": "Allow", "Action": ["*"], "Resource": "*"}})})
    assert report_for(d)["severity_score"] == 85


def test_failed_attempt_lowers_score_and_only_suggests_investigation():
    d = detail("authorize_sg_ingress.json")
    d["errorCode"] = "UnauthorizedOperation"
    r = report_for(d)
    assert r["severity_score"] == 55 and r["severity"] == "MEDIUM"
    assert len(r["remediation"]) == 1
    assert "nothing changed" in r["remediation"][0]["step"]


def test_root_actor_raises_score():
    d = detail("deactivate_mfa_device.json")
    d["userIdentity"] = {"type": "Root", "arn": "arn:aws:iam::123456789012:root", "accountId": "123456789012"}
    r = report_for(d)
    assert r["severity_score"] == 95 and r["severity"] == "CRITICAL"
    assert any("root" in s["step"] for s in r["remediation"])


def test_private_cidr_is_not_internet_exposure():
    d = detail("authorize_sg_ingress.json")
    d["requestParameters"]["ipPermissions"]["items"][0]["ipRanges"]["items"][0]["cidrIp"] = "10.0.0.0/8"
    r = report_for(d)
    assert r["severity_score"] == 50 and r["severity"] == "MEDIUM"


def test_all_traffic_ipv6_rule():
    d = detail("authorize_sg_ingress.json")
    d["requestParameters"]["ipPermissions"]["items"][0].update(
        ipProtocol="-1", fromPort=None, toPort=None, ipRanges={},
        ipv6Ranges={"items": [{"cidrIpv6": "::/0"}]})
    r = report_for(d)
    assert r["severity_score"] == 80
    cmd = next(s["command"] for s in r["remediation"] if "revoke" in (s["command"] or ""))
    assert "Ipv6Ranges=[{CidrIpv6=::/0}]" in cmd and "IpProtocol=-1" in cmd


def test_same_account_trust_is_not_cross_account():
    d = detail("update_assume_role_policy.json")
    d["requestParameters"]["policyDocument"] = json.dumps({"Statement": [
        {"Effect": "Allow", "Principal": {"AWS": "arn:aws:iam::123456789012:root"}, "Action": "sts:AssumeRole"}]})
    assert report_for(d)["severity_score"] == 70


def test_wildcard_trust_is_worst_case():
    d = detail("update_assume_role_policy.json")
    d["requestParameters"]["policyDocument"] = json.dumps({"Statement": [
        {"Effect": "Allow", "Principal": "*", "Action": "sts:AssumeRole"}]})
    r = report_for(d)
    assert r["severity_score"] == 100
    assert any("ANY AWS principal" in f["factor"] for f in r["score_factors"])


def test_public_bucket_policy_raises_score():
    r = ip.build_report(json.loads((EVENTS / "put_bucket_policy.json").read_text()))
    assert r["severity_score"] == 65  # sample policy is a Deny, not public
    d = copy.deepcopy(json.loads((EVENTS / "put_bucket_policy.json").read_text())["detail"])
    d["requestParameters"]["bucketPolicy"] = {"Statement": [
        {"Effect": "Allow", "Principal": "*", "Action": "s3:GetObject", "Resource": "arn:aws:s3:::b/*"}]}
    assert report_for(d)["severity_score"] == 80


def test_score_is_clamped_to_0_100():
    d = detail("update_assume_role_policy.json")
    d["userIdentity"] = {"type": "Root", "arn": "arn:aws:iam::123456789012:root"}
    d["requestParameters"]["policyDocument"] = json.dumps({"Statement": [
        {"Effect": "Allow", "Principal": "*", "Action": "sts:AssumeRole"}]})
    assert report_for(d)["severity_score"] == 100


@pytest.mark.parametrize("score,band", [(100, "CRITICAL"), (85, "CRITICAL"), (84, "HIGH"), (60, "HIGH"),
                                        (59, "MEDIUM"), (35, "MEDIUM"), (34, "LOW"), (0, "LOW")])
def test_severity_bands(score, band):
    assert ip.severity_for(score) == band


# --- remediation commands use the real resource names --------------------------

def test_remediation_commands_are_specific():
    cases = {
        "create_access_key.json": "aws iam update-access-key --user-name support-backup --access-key-id AKIASYNTHETIC0002 --status Inactive",
        "deactivate_mfa_device.json": "aws iam list-mfa-devices --user-name admin-ops",
        "update_assume_role_policy.json": "aws iam get-role --role-name prod-deploy-role --query Role.AssumeRolePolicyDocument",
        "authorize_sg_ingress.json": "aws ec2 revoke-security-group-ingress --group-id sg-0a1b2c3d4e5f60718 --protocol tcp --port 22 --cidr 0.0.0.0/0",
        "schedule_key_deletion.json": "aws kms cancel-key-deletion --key-id arn:aws:kms:us-east-1:123456789012:key/1a2b3c4d-1111-4a4a-8b8b-0c0c0c0c0c01",
    }
    for f, expected in cases.items():
        cmds = [s["command"] for s in ip.build_report(load(f))["remediation"]]
        assert expected in cmds, (f, cmds)


def test_kms_remediation_re_enables_after_cancel():
    cmds = [s["command"] for s in ip.build_report(load("schedule_key_deletion.json"))["remediation"]]
    assert cmds.index(next(c for c in cmds if c and "cancel-key-deletion" in c)) < \
        cmds.index(next(c for c in cmds if c and "enable-key" in c and "cancel" not in c))


def test_original_categories_get_remediation_too():
    r = ip.build_report(json.loads((EVENTS / "stop_logging.json").read_text()))
    assert "aws cloudtrail start-logging --name aws-sec-ir-trail" in [s["command"] for s in r["remediation"]]
    r = ip.build_report(json.loads((EVENTS / "attach_user_policy.json").read_text()))
    assert any(s["command"] and s["command"].startswith("aws iam detach-user-policy --user-name aws-sec-ir-test-user")
               for s in r["remediation"])
